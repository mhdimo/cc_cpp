// Generates `src/ui/code_languages.cpp` from the language definitions of
// highlight.js.
//
// The reference highlights a block of code with `cli-highlight`, which wraps
// highlight.js; the keywords of a language therefore come from highlight.js
// and the colours come from the theme of cli-highlight. This script writes
// the keyword lists into the port, so that the same words are recognised.
//
//   node scripts/generate-code-languages.mjs
//
// It needs highlight.js to be installed (`npm install highlight.js`).

