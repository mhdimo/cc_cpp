// The scopes highlight.js knows. The order is the order of the enum in
// `src/ui/code_languages.hpp`.
const SCOPES = [
  'keyword',
  'built_in',
  'type',
  'literal',
  'title',
  'symbol',
  'meta',
  'attr',
  'name',
  'variable',
  'doctag',
  'section',
  'meta-keyword',
  'meta-string',
  'template-variable',
  'params',
  'class',
  'function',
  'regexp',
  'subst',
]

// The scope a word belongs to when the language has none of its own.
const FALLBACK_SCOPE = 'keyword'

const escape = (word) => word.replace(/\\/g, '\\\\').replace(/"/g, '\\"')

const lines = []
lines.push('// Generated by scripts/generate-code-languages.mjs — do not edit.')
lines.push('//')
lines.push('// The keyword lists come from highlight.js ' +
           require('highlight.js/package.json').version +
           ', the highlighter the reference uses through cli-highlight.')
lines.push('')
lines.push('#include "ui/code_languages.hpp"')
lines.push('')
lines.push('namespace cc::ui::code {')
lines.push('')

for (const language of LANGUAGES) {
  const definition = hljs.getLanguage(language.name)
  if (!definition || !definition.keywords) {
    console.error('skipping the unknown language ' + language.name)
    continue
  }

  const aliases = [language.name, ...(definition.aliases ?? [])]
  lines.push('const char* const k' + camel(language.name) + 'Aliases[] = {' +
             aliases.map((alias) => '"' + escape(alias) + '"').join(', ') + '};')

  for (const scope of SCOPES) {
    const list = definition.keywords[scope]
    if (!list) continue

    const words = (Array.isArray(list) ? list : String(list).split(' '))
      .filter((word) => word && !word.includes('|') && !word.includes('('))
      .sort()
    if (words.length === 0) continue

    lines.push('const char* const k' + camel(language.name) + capitalize(scope) + '[] = {' +
               words.map((word) => '"' + escape(word) + '"').join(', ') + '};')
  }
  lines.push('')
}

// The table that ties the lists together.
lines.push('const LanguageDefinition kDefinitions[] = {')
for (const language of LANGUAGES) {
  const definition = hljs.getLanguage(language.name)
  if (!definition || !definition.keywords) continue

  const aliases = [language.name, ...(definition.aliases ?? [])]
  const scopes = []
  for (const scope of SCOPES) {
    const list = definition.keywords[scope]
    if (!list) continue
    const words = (Array.isArray(list) ? list : String(list).split(' '))
      .filter((word) => word && !word.includes('|') && !word.includes('('))
    if (words.length === 0) continue
    scopes.push({ scope, name: camel(language.name) + capitalize(scope) })
  }

  lines.push('    {')
  lines.push('        .name = "' + escape(language.name) + '",')
  lines.push('        .aliases = k' + camel(language.name) + 'Aliases,')
  lines.push('        .alias_count = ' + aliases.length + ',')
  lines.push('        .comments = CommentStyle::' + commentStyle(language.comments) + ',')
  if (language.block) {
    lines.push('        .block_comment = BlockComment::' +
               (language.block === 'angle' ? 'Angle' : language.block === true ? 'Slash' : 'None') + ',')
  }
  if (language.backtick) lines.push('        .backtick_strings = true,')
  if (language.triple) lines.push('        .triple_strings = true,')
  lines.push('        .scopes = {')
  for (const scope of scopes) {
    lines.push('            {Scope::' + scopeClass(scope.scope) + ', k' + scope.name + '},')
  }
  lines.push('        },')
  lines.push('    },')
}
lines.push('};')
lines.push('')
lines.push('const LanguageDefinition* definitions() { return kDefinitions; }')
lines.push('')
lines.push('size_t definition_count() { return sizeof(kDefinitions) / sizeof(kDefinitions[0]); }')
lines.push('')
lines.push('} // namespace cc::ui::code')
lines.push('')

writeFileSync(join(here, '..', 'src', 'ui', 'code_languages.cpp'), lines.join('\n'))
console.log('wrote src/ui/code_languages.cpp')

function camel(name) {
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
}

function capitalize(text) {
  return text.charAt(0).toUpperCase() + text.slice(1).replace(/-([a-z])/g, (_, c) => c.toUpperCase())
}

function scopeClass(scope) {
  return capitalize(scope).replace(/-([a-z])/g, (_, c) => c.toUpperCase())
}

function commentStyle(style) {
  switch (style) {
    case 'c': return 'CLike'
    case 'hash': return 'Hash'
    case 'semi': return 'Semi'
    case 'block': return 'Block'
    case 'quote': return 'Quote'
    case 'percent': return 'Percent'
    case 'xml': return 'Xml'
    default: return 'None'
  }
}
